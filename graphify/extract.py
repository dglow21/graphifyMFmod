def _mf_self_consistent(nodes: list, edges: list) -> list:
    """Drop edges whose endpoints aren't in this extraction's node set, and
    deduplicate by (source, relation, target). CALL/COPY/PERFORM targets are all
    emitted as nodes here, so anything left dangling is a genuine external/typo
    reference that build_graph would discard anyway."""
    ids = {n["id"] for n in nodes}
    out, seen = [], set()
    for e in edges:
        if e["source"] not in ids or e["target"] not in ids:
            continue
        key = (e["source"], e["relation"], e["target"])
        if key in seen:
            continue
        seen.add(key)
        out.append(e)
    return out


def _mf_merge(base: dict, extra: dict | None) -> dict:
    """Combine the regex COBOL extractor (the trustworthy base — robust against
    fixed/free format and IBM/GnuCOBOL dialect extensions) with the ProLeap ANTLR
    parse (which adds precise paragraph-scoped call attribution when it parses
    cleanly). Definitions discovered only by the ANTLR pass are *not* trusted —
    on a partial/recovered parse it can mistake mis-tokenised statements for
    paragraph names — so its ``defines`` targets are kept only when the regex base
    already found them. Its call/use edges are merged and then filtered to the
    base's node set, so a bad parse can never inject spurious nodes."""
    if not extra:
        return base
    base_ids = {n["id"] for n in base["nodes"]}
    extra_def_targets = {e["target"] for e in extra.get("edges", []) if e["relation"] == "defines"}
    nodes = list(base["nodes"])
    have = set(base_ids)
    for n in extra.get("nodes", []):
        if n["id"] in have:
            continue
        if n["id"] in extra_def_targets:
            continue  # an ANTLR-only "definition" — don't trust it over the regex base
        nodes.append(n)
        have.add(n["id"])
    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, list(base["edges"]) + list(extra.get("edges", [])))}


# COBOL column-7 indicators that mean "this line is not code".
_COBOL_NONCODE_INDICATORS = frozenset("*/$")
# Words that follow PERFORM but are not procedure names (inline PERFORM clauses).
_COBOL_NON_PROCEDURE = frozenset({
    "UNTIL", "VARYING", "TIMES", "TEST", "WITH", "BEFORE", "AFTER", "FOREVER", "THRU", "THROUGH",
})
# One-word COBOL sentences that look like a paragraph header but are statements,
# plus data-division entry types and embedded-SQL/CICS keywords that can leak
# through as bogus "paragraph names" on a partial parse.
_COBOL_NON_PARAGRAPH = frozenset({
    "EXIT", "CONTINUE", "GOBACK", "FD", "SD", "RD", "CD", "END", "EXEC", "END-EXEC",
    "CICS", "SQL", "SQLIMS", "DLI", "LINK", "XCTL", "PROGRAM", "COMMAREA", "MAP", "MAPSET",
})
# Tokens that can follow FROM/JOIN/UPDATE in embedded SQL but aren't table names.
_SQL_NON_TABLE = frozenset({"TABLE", "LATERAL", "ONLY", "FINAL", "OLD", "NEW", "SELECT", "VALUES", "DUAL"})


def _sql_table_id(name: str) -> str:
    """Stable, file-independent node id for a SQL/DB2 table or view, keyed on the
    unqualified (short) name. Lets embedded ``EXEC SQL`` references in COBOL link
    to the DDL that defines the table, and cross-file foreign keys resolve, even
    though COBOL often uses the unqualified name while DDL is schema-qualified."""
    short = name.strip().strip("\"'`[]").split(".")[-1].strip("\"'`[]")
    return _make_id("tbl", short)


def _blank_keep_newlines(text: str) -> str:
    return re.sub(r"[^\n]", " ", text)


def _decolumn_cobol(text: str) -> str:
    """Best-effort port of the ProLeap COBOL preprocessor's line handling: detect
    fixed vs. free source format, drop comment/debug lines, and join ``-``
    continuation lines (handling continued non-numeric literals). Newlines are
    preserved so token/line numbers still line up with the original file."""
    raw = text.splitlines()
    fixed_votes = free_votes = seq_votes = nonblank = 0
    for ln in raw:
        s = ln.rstrip()
        if not s.strip():
            continue
        nonblank += 1
        area_seq = s[:6]
        ind = s[6] if len(s) > 6 else " "
        if area_seq.strip().isdigit():
            seq_votes += 1
        if (area_seq.strip() == "" or area_seq.strip().isdigit()) and (len(s) <= 6 or ind in " *$/-Dd"):
            fixed_votes += 1
        elif s[:1] not in (" ", "\t", "*"):
            free_votes += 1
    fixed = fixed_votes >= 3 and fixed_votes >= free_votes
    # Only cap code at column 72 when the file actually carries sequence numbers in
    # columns 1-6 — that signals "true" reference format (so cols 73-80 are the
    # identification area, not code). Otherwise keep everything after column 7:
    # plenty of real COBOL is just indented to column 8 but lets code run past 72.
    code_end = 72 if (nonblank and seq_votes >= max(3, nonblank // 2)) else None

    out: list[str] = []
    for ln in raw:
        s = ln.rstrip("\n").rstrip("\r")
        if fixed:
            ind = s[6] if len(s) > 6 else " "
            if ind in _COBOL_NONCODE_INDICATORS:
                out.append("")
                continue
            code = (s[7:code_end] if code_end else s[7:]) if len(s) > 7 else ""
            if ind == "-" and out:
                prev = out[-1].rstrip()
                cont = code.lstrip()
                # Continuation of a non-numeric literal: the resume quote on the
                # continuation line is a delimiter, not part of the literal value.
                if cont[:1] in ("'", '"') and prev.count(cont[0]) % 2 == 1:
                    cont = cont[1:]
                out[-1] = prev + cont
                out.append("")
                continue
            out.append(code)
        else:
            stripped = s.lstrip()
            if stripped.startswith("*>") or s[:1] == "*":
                out.append("")
                continue
            out.append(s)
    return "\n".join(out)


def _strip_cobol_for_grammar(deco: str) -> tuple[str, list[str]]:
    """Turn de-columned COBOL into something the bare ProLeap COBOL85 grammar can
    parse (the grammar expects preprocessed input): blank IDENTIFICATION-DIVISION
    comment entries (AUTHOR./INSTALLATION./...), ``COPY``/``REPLACE`` statements,
    compiler directives, and ``EXEC SQL|CICS|DLI`` blocks. Returns the stripped
    source plus the list of ``COPY`` member names that were removed."""
    kept: list[str] = []
    in_id_division = False
    for ln in deco.split("\n"):
        u = ln.lstrip().upper()
        if re.match(r"^(?:IDENTIFICATION|ID)[ \t]+DIVISION\b", u):
            in_id_division = True
            kept.append(ln)
            continue
        if in_id_division:
            if re.match(r"^(?:ENVIRONMENT|DATA|PROCEDURE)[ \t]+DIVISION\b", u):
                in_id_division = False
                kept.append(ln)
                continue
            if re.match(r"^PROGRAM-ID\b", u):
                kept.append(ln)
                continue
            kept.append(_blank_keep_newlines(ln))
            continue
        kept.append(ln)
    src = "\n".join(kept)

    copybooks: list[str] = []

    def _copy_repl(m):
        copybooks.append(m.group(1).strip("'\""))
        return _blank_keep_newlines(m.group(0))

    src = re.sub(
        r"(?ims)^[ \t]*COPY\b[ \t]+([\w$#@-]+|'[^'\n]+'|\"[^\"\n]+\")"
        r"(?:[ \t]+(?:OF|IN)[ \t]+[\w$#@-]+)?(?:[ \t]+SUPPRESS\b)?(?:[ \t\n]+REPLACING\b.*?)?\.",
        _copy_repl, src,
    )
    src = re.sub(r"(?ims)^[ \t]*REPLACE\b.*?\.", lambda m: _blank_keep_newlines(m.group(0)), src)
    src = re.sub(r"(?im)^[ \t]*(?:EJECT|SKIP[123]|TITLE\b[^\n]*|>>[^\n]*)[ \t]*\.?[ \t]*$",
                 lambda m: _blank_keep_newlines(m.group(0)), src)
    src = re.sub(r"(?is)\bEXEC\b[ \t]+(?:SQL(?:IMS)?|CICS|DL/?I|ADS)\b.*?\bEND[ \t-]?EXEC\b[ \t]*\.?",
                 lambda m: _blank_keep_newlines(m.group(0)), src)
    return src, copybooks


def _quote_balanced_before(line_text: str, idx: int) -> bool:
    """True if ``idx`` in ``line_text`` is outside any quoted literal (i.e. an even
    number of quote characters precede it). Used to skip keyword-like substrings
    inside COBOL string literals (e.g. ``DISPLAY 'PLEASE CALL SUPPORT'``)."""
    prefix = line_text[:idx]
    return prefix.count("'") % 2 == 0 and prefix.count('"') % 2 == 0


def _cobol_antlr_extract(path: Path, grammar_src: str) -> dict | None:
    """Parse grammar-ready COBOL with the vendored ProLeap COBOL85 ANTLR4 grammar.

    Returns an extraction dict, or ``None`` if the optional ``antlr4-python3-runtime``
    is missing, the file is too large, or the parse recovered no structure."""
    if len(grammar_src) > 4_000_000:  # very large source — skip the (slower) full parse
        return None
    try:
        from antlr4 import InputStream, CommonTokenStream, ParseTreeWalker, PredictionMode
        from antlr4.error.ErrorListener import ErrorListener
        from graphify._antlr.cobol85.Cobol85Lexer import Cobol85Lexer
        from graphify._antlr.cobol85.Cobol85Parser import Cobol85Parser
        from graphify._antlr.cobol85.Cobol85Listener import Cobol85Listener
    except ImportError:
        return None

    class _SilentErrors(ErrorListener):
        def syntaxError(self, *_a, **_k):
            pass

        def reportAmbiguity(self, *_a, **_k):
            pass

        def reportAttemptingFullContext(self, *_a, **_k):
            pass

        def reportContextSensitivity(self, *_a, **_k):
            pass

    try:
        lexer = Cobol85Lexer(InputStream(grammar_src))
        lexer.removeErrorListeners()
        lexer.addErrorListener(_SilentErrors())
        parser = Cobol85Parser(CommonTokenStream(lexer))
        parser.removeErrorListeners()
        parser.addErrorListener(_SilentErrors())
        # SLL is much faster than the default LL prediction; mispredictions on the
        # (intentionally permissive) COBOL grammar are reported as errors and
        # recovered, which is fine for structural extraction.
        parser._interp.predictionMode = PredictionMode.SLL
        tree = parser.startRule()
    except Exception:
        return None

    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None) -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc))
            seen.add(nid)

    def _clean(text: str) -> str:
        return text.strip().strip("'\"").strip()

    class _Walk(Cobol85Listener):
        def __init__(self):
            self.prog_stack: list[str] = []
            self.cur_para: str | None = None
            self.found_paragraph = False

        @property
        def cur_prog(self) -> str | None:
            return self.prog_stack[-1] if self.prog_stack and self.prog_stack[-1] else None

        def _scope(self) -> str:
            if self.cur_prog and self.cur_para:
                return _make_id(self.cur_prog, self.cur_para)
            if self.cur_prog:
                return _make_id(self.cur_prog)
            return file_nid

        def enterProgramUnit(self, ctx):
            self.prog_stack.append("")
            self.cur_para = None

        def exitProgramUnit(self, ctx):
            if self.prog_stack:
                self.prog_stack.pop()
            self.cur_para = None

        def enterProgramIdParagraph(self, ctx):
            pn = ctx.programName()
            if pn is None:
                return
            name = _clean(pn.getText())
            if not name:
                return
            if self.prog_stack:
                self.prog_stack[-1] = name
            else:
                self.prog_stack.append(name)
            nid = _make_id(name)
            _add(nid, name, _mf_loc(ctx))
            edges.append(_mf_edge(file_nid, nid, "defines", str_path, _mf_loc(ctx)))

        def enterProcedureSection(self, ctx):
            hdr = ctx.procedureSectionHeader()
            if hdr is None or hdr.sectionName() is None or not self.cur_prog:
                return
            name = _clean(hdr.sectionName().getText())
            if not name:
                return
            self.found_paragraph = True
            nid = _make_id(self.cur_prog, name)
            _add(nid, name, _mf_loc(ctx))
            edges.append(_mf_edge(_make_id(self.cur_prog), nid, "defines", str_path, _mf_loc(ctx)))
            self.cur_para = None

        def enterParagraph(self, ctx):
            pn = ctx.paragraphName()
            if pn is None or not self.cur_prog:
                return
            name = _clean(pn.getText())
            if not name:
                return
            self.found_paragraph = True
            self.cur_para = name
            nid = _make_id(self.cur_prog, name)
            _add(nid, name, _mf_loc(ctx))
            edges.append(_mf_edge(_make_id(self.cur_prog), nid, "defines", str_path, _mf_loc(ctx)))

        def exitParagraph(self, ctx):
            self.cur_para = None

        def enterCallStatement(self, ctx):
            lit = ctx.literal()
            if lit is None:
                return  # dynamic CALL through a data item — callee not known statically
            target = _clean(lit.getText())
            if not target:
                return
            tnid = _make_id(target)
            _add(tnid, target)
            edges.append(_mf_edge(self._scope(), tnid, "calls", str_path, _mf_loc(ctx)))

        def enterPerformProcedureStatement(self, ctx):
            if not self.cur_prog:
                return
            for pn in ctx.procedureName():
                target = None
                if pn.paragraphName() is not None:
                    target = _clean(pn.paragraphName().getText())
                elif pn.sectionName() is not None:
                    target = _clean(pn.sectionName().getText())
                if not target or target.upper() in _COBOL_NON_PROCEDURE:
                    continue
                tnid = _make_id(self.cur_prog, target)
                edges.append(_mf_edge(self._scope(), tnid, "calls", str_path, _mf_loc(ctx)))

        def enterGoToStatement(self, ctx):
            if not self.cur_prog:
                return
            try:
                names = ctx.procedureName()
            except AttributeError:
                names = []
            for pn in names or []:
                target = None
                if pn.paragraphName() is not None:
                    target = _clean(pn.paragraphName().getText())
                elif pn.sectionName() is not None:
                    target = _clean(pn.sectionName().getText())
                if not target:
                    continue
                edges.append(_mf_edge(self._scope(), _make_id(self.cur_prog, target),
                                      "calls", str_path, _mf_loc(ctx), conf="INFERRED", score=0.7))

    walker = _Walk()
    try:
        ParseTreeWalker().walk(walker, tree)
    except Exception:
        return None

    if not walker.found_paragraph and len(nodes) <= 2:
        return None  # parse recovered nothing useful — let the regex extractor stand
    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


def _cobol_para_index(nodes: list[dict], exclude_ids: set[str]) -> list[tuple[int, str]]:
    """Sorted (line, node_id) list of paragraph/section definitions, for resolving
    which paragraph a statement at a given line belongs to."""
    idx = []
    for n in nodes:
        if n["id"] in exclude_ids:
            continue
        loc = n.get("source_location")
        if isinstance(loc, str) and loc.startswith("L") and loc[1:].isdigit():
            idx.append((int(loc[1:]), n["id"]))
    return sorted(idx)


def _cobol_regex_extract(path: Path, deco: str, copybooks: list[str]) -> dict:
    """Structural COBOL extractor that works on de-columned source with plain
    regexes — programs, sections, paragraphs, CALL/PERFORM/GO-TO call edges scoped
    to the enclosing paragraph, COPY dependencies, and embedded SQL/CICS
    references. Robust against dialect extensions the bare grammar can't parse and
    used as the base layer for :func:`extract_cobol`."""
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None, ftype: str = "code") -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc, ftype))
            seen.add(nid)

    lines = deco.split("\n")
    line_starts = [0]
    for ln in lines:
        line_starts.append(line_starts[-1] + len(ln) + 1)

    def _line_no(idx: int) -> int:
        return bisect.bisect_right(line_starts, idx)

    progs: list[tuple[int, str]] = []  # (line, program-name)
    for m in re.finditer(r"(?im)^[ \t]*PROGRAM-ID[ \t]*\.[ \t]*([\w$#@-]+|'[^']+'|\"[^\"]+\")", deco):
        name = m.group(1).strip("'\"")
        if not name:
            continue
        ln_no = _line_no(m.start())
        progs.append((ln_no, name))
        nid = _make_id(name)
        _add(nid, name, f"L{ln_no}")
        edges.append(_mf_edge(file_nid, nid, "defines", str_path, f"L{ln_no}"))
    if not progs:
        fallback = _file_stem(path).split(".")[-1].upper()
        progs = [(1, fallback)]
        _add(_make_id(fallback), fallback)
        edges.append(_mf_edge(file_nid, _make_id(fallback), "defines", str_path))
    progs.sort()
    prog = progs[0][1]
    prog_nid = _make_id(prog)
    prog_lines = [p[0] for p in progs]
    prog_nids_all = {_make_id(p[1]) for p in progs}

    def _prog_at(line_no: int) -> tuple[str, str]:
        # The program whose PROGRAM-ID precedes this line (for nested/contained programs).
        pos = bisect.bisect_right(prog_lines, line_no) - 1
        name = progs[pos][1] if pos >= 0 else prog
        return _make_id(name), name

    proc_idx = next((i for i, ln in enumerate(lines) if re.match(r"(?i)^[ \t]*PROCEDURE[ \t]+DIVISION\b", ln)), None)
    if proc_idx is not None:
        for i in range(proc_idx + 1, len(lines)):
            # Paragraph / section names live in Area A — the very start of the
            # de-columned line; statements in Area B are indented.
            m = re.match(r"^([A-Za-z0-9][\w$#@-]*)[ \t]*(SECTION)?[ \t]*\.[ \t]*$", lines[i])
            if not m or m.group(1).upper() in _COBOL_NON_PARAGRAPH:
                continue
            name = m.group(1)
            owner_nid, owner_name = _prog_at(i + 1)
            nid = _make_id(owner_name, name)
            _add(nid, name, f"L{i + 1}")
            edges.append(_mf_edge(owner_nid, nid, "defines", str_path, f"L{i + 1}"))

    para_index = _cobol_para_index(nodes, prog_nids_all | {file_nid})

    def _scope_at(line_no: int) -> str:
        if para_index:
            pos = bisect.bisect_right(para_index, (line_no, "￿")) - 1
            if pos >= 0:
                return para_index[pos][1]
        return _prog_at(line_no)[0]

    def _emit_edge(line_no: int, target_nid: str, relation: str = "calls", *, conf="EXTRACTED", score=1.0):
        edges.append(_mf_edge(_scope_at(line_no), target_nid, relation, str_path, f"L{line_no}",
                              conf=conf, score=score))

    # CALL 'literal'  (static program call). Skip matches inside string literals.
    for m in re.finditer(r"(?i)\bCALL\b[ \t]+(?:'([^'\n]+)'|\"([^\"\n]+)\")", deco):
        line_no = _line_no(m.start())
        if not _quote_balanced_before(lines[line_no - 1], m.start() - line_starts[line_no - 1]):
            continue
        target = (m.group(1) or m.group(2)).strip()
        if not target:
            continue
        tnid = _make_id(target)
        _add(tnid, target)
        _emit_edge(line_no, tnid)

    # CANCEL 'literal'  (unloads a subprogram — a reference, not a call).
    for m in re.finditer(r"(?i)\bCANCEL\b[ \t]+(?:'([^'\n]+)'|\"([^\"\n]+)\")", deco):
        line_no = _line_no(m.start())
        if not _quote_balanced_before(lines[line_no - 1], m.start() - line_starts[line_no - 1]):
            continue
        target = (m.group(1) or m.group(2)).strip()
        if not target:
            continue
        tnid = _make_id(target)
        _add(tnid, target)
        _emit_edge(line_no, tnid, "references", conf="INFERRED", score=0.6)

    # PERFORM para [THRU/THROUGH para]   (only when followed by an identifier, not
    # an inline PERFORM body like "PERFORM 5 TIMES" or "PERFORM UNTIL ...").
    for m in re.finditer(r"(?i)\bPERFORM\b[ \t]+([A-Za-z0-9][\w$#@-]*)(?:[ \t]+(?:THRU|THROUGH)[ \t]+([A-Za-z0-9][\w$#@-]*))?", deco):
        line_no = _line_no(m.start())
        _, owner_name = _prog_at(line_no)
        for g in (m.group(1), m.group(2)):
            if not g or g.upper() in _COBOL_NON_PROCEDURE or g.upper() in _COBOL_NON_PARAGRAPH:
                continue
            _emit_edge(line_no, _make_id(owner_name, g))

    # GO TO para  (unconditional branch; treated as a weak call edge).
    for m in re.finditer(r"(?i)\bGO(?:[ \t]+TO|TO)\b[ \t]+([A-Za-z0-9][\w$#@-]*)", deco):
        line_no = _line_no(m.start())
        g = m.group(1)
        if g.upper() in _COBOL_NON_PARAGRAPH or g.upper() == "DEPENDING":
            continue
        _emit_edge(line_no, _make_id(_prog_at(line_no)[1], g), conf="INFERRED", score=0.7)

    # COPY members (also re-scanned here in case they survived the grammar strip).
    members = list(dict.fromkeys(copybooks))
    for m in re.finditer(r"(?im)^[ \t]*COPY\b[ \t]+([\w$#@-]+|'[^'\n]+'|\"[^\"\n]+\")", deco):
        members.append(m.group(1).strip("'\""))
    for cb in dict.fromkeys(members):
        cb = cb.strip()
        if not cb:
            continue
        cbid = _make_id(cb)
        _add(cbid, cb)
        edges.append(_mf_edge(file_nid, cbid, "includes", str_path))

    # Embedded SQL / CICS — the grammar can't see inside these (they're stripped
    # for the parse), so mine them with regexes for table / program / map deps.
    for m in re.finditer(r"(?is)\bEXEC\b[ \t]+(SQL(?:IMS)?|CICS|DL/?I|ADS)\b(.*?)\bEND[ \t-]?EXEC\b", deco):
        kind = m.group(1).upper()
        body = m.group(2)
        line_no = _line_no(m.start())
        scope = _scope_at(line_no)
        if kind.startswith("SQL"):
            inc = re.match(r"(?is)^[ \t\n]*INCLUDE\b[ \t]+([\w$#@-]+)", body)
            if inc:
                mem = inc.group(1)
                _add(_make_id(mem), mem)
                edges.append(_mf_edge(file_nid, _make_id(mem), "includes", str_path, f"L{line_no}"))
                continue
            for tm in re.finditer(r"(?is)\b(?:FROM|JOIN|INSERT[ \t]+INTO|UPDATE|DELETE[ \t]+FROM)\b[ \t]+([A-Za-z_][\w$#@]*(?:\.[A-Za-z_][\w$#@]*)*)", body):
                tbl = tm.group(1)
                if tbl.split(".")[-1].upper() in _SQL_NON_TABLE:
                    continue
                tnid = _sql_table_id(tbl)
                _add(tnid, tbl, ftype="concept")
                edges.append(_mf_edge(scope, tnid, "uses", str_path, f"L{line_no}", conf="INFERRED", score=0.7))
        elif kind == "CICS":
            lk = re.search(r"(?is)\b(?:LINK|XCTL)\b.*?\bPROGRAM\b[ \t]*\([ \t]*'([^'\n]+)'", body)
            if lk:
                pg = lk.group(1).strip()
                _add(_make_id(pg), pg)
                edges.append(_mf_edge(scope, _make_id(pg), "calls", str_path, f"L{line_no}"))
            mp = re.search(r"(?is)\b(?:SEND|RECEIVE)\b.*?\bMAP\b[ \t]*\([ \t]*'([^'\n]+)'", body)
            if mp:
                name = mp.group(1).strip()
                _add(_make_id("map", name), name, ftype="concept")
                edges.append(_mf_edge(scope, _make_id("map", name), "uses", str_path, f"L{line_no}", conf="INFERRED", score=0.7))
            ms = re.search(r"(?is)\bMAPSET\b[ \t]*\([ \t]*'([^'\n]+)'", body)
            if ms:
                name = ms.group(1).strip()
                _add(_make_id(name), name)
                edges.append(_mf_edge(scope, _make_id(name), "uses", str_path, f"L{line_no}", conf="INFERRED", score=0.6))
            fl = re.search(r"(?is)\b(?:FILE|DATASET)\b[ \t]*\([ \t]*'([^'\n]+)'", body)
            if fl:
                name = fl.group(1).strip()
                _add(_make_id("dsn", name), name, ftype="concept")
                edges.append(_mf_edge(scope, _make_id("dsn", name), "uses", str_path, f"L{line_no}", conf="INFERRED", score=0.7))

    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


def extract_cobol(path: Path) -> dict:
    """Extract programs, sections, paragraphs, CALL/PERFORM/GO-TO call edges, COPY
    dependencies and embedded SQL/CICS references from a COBOL source file.

    A regex-based structural extractor (robust against IBM/GnuCOBOL dialect
    extensions and fixed/free format) forms the base layer; when the optional
    ``antlr4-python3-runtime`` is installed, the file is also parsed with the
    vendored ProLeap COBOL 85 ANTLR4 grammar and its precise paragraph-scoped call
    edges are merged in."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    deco = _decolumn_cobol(src)
    grammar_src, copybooks = _strip_cobol_for_grammar(deco)
    base = _cobol_regex_extract(path, deco, copybooks)
    antlr = _cobol_antlr_extract(path, grammar_src)
    return _mf_merge(base, antlr)


def extract_copybook(path: Path) -> dict:
    """Extract top-level record names (01/77-level data items) and nested COPY
    dependencies from a COBOL copybook.

    Copybooks are data definitions, not full programs, so they get a lightweight
    record-level extraction rather than the COBOL85 program grammar. The copybook
    file node is keyed on its member name so ``COPY`` edges from programs link to it."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    deco = _decolumn_cobol(src)
    str_path = str(path)
    member = _file_stem(path).split(".")[-1]
    file_nid = _make_id(member)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}
    for i, ln in enumerate(deco.split("\n")):
        m = re.match(r"^[ \t]*(0?1|77)[ \t]+([A-Za-z][\w$#@-]*)\b", ln)
        if m:
            name = m.group(2)
            if name.upper() != "FILLER":
                nid = _make_id(member, name)
                if nid not in seen:
                    seen.add(nid)
                    nodes.append(_mf_node(nid, name, str_path, f"L{i + 1}"))
                    edges.append(_mf_edge(file_nid, nid, "defines", str_path, f"L{i + 1}"))
            continue
        cm = re.match(r"(?i)^[ \t]*COPY\b[ \t]+([\w$#@-]+|'[^'\n]+'|\"[^\"\n]+\")", ln)
        if cm:
            cb = cm.group(1).strip("'\"")
            cbid = _make_id(cb)
            if cbid not in seen:
                seen.add(cbid)
                nodes.append(_mf_node(cbid, cb, str_path))
            edges.append(_mf_edge(file_nid, cbid, "includes", str_path, f"L{i + 1}"))
    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


def extract_jcl(path: Path) -> dict:
    """Extract jobs, in-stream procedures, steps (EXEC PGM=/PROC=), DD dataset
    reads/writes, and INCLUDE members from a JCL (Job Control Language) member."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None, ftype: str = "code") -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc, ftype))
            seen.add(nid)

    stem = _file_stem(path).split(".")[-1]
    cur_job: str | None = None
    cur_proc: str | None = None  # in-stream PROC currently being defined
    cur_step_nid: str | None = None
    prev_was_dd = False
    # A cataloged-procedure member (in a PROCLIB) is just steps — no JOB and often
    # no //name PROC card. Treat the member name as a procedure so EXEC PROC=member
    # references from other JCL link to it.
    src_lines = src.splitlines()
    if not any(re.match(r"^//\S+\s+JOB\b", x) or re.match(r"^//\S+\s+PROC\b", x) for x in src_lines):
        cur_proc = stem
        pid = _make_id(stem)
        _add(pid, stem, "L1")
        edges.append(_mf_edge(file_nid, pid, "defines", str_path, "L1"))
    for i, raw in enumerate(src_lines):
        ln = raw.rstrip()
        if ln.startswith("//*") or not ln.startswith("//"):
            prev_was_dd = False
            continue
        body = ln[2:]
        loc = f"L{i + 1}"
        m = re.match(r"^([A-Z0-9#@$]{1,8})?\s+(\S+)\s*(.*)$", body)
        # A nameless line whose first token looks like an operand fragment
        # (KEYWORD=value) is a continuation of the previous statement.
        is_continuation = (m is None) or (m.group(1) is None and m.group(2) != "DD" and "=" in m.group(2))
        if is_continuation:
            if prev_was_dd:
                cont = re.search(r"\bDSN(?:AME)?=([A-Z0-9#@$.()+\-]+)", body, re.I)
                if cont:
                    name_only = cont.group(1).split("(")[0]
                    dn = _make_id("dsn", name_only)
                    _add(dn, name_only, ftype="concept")
                    src_nid = cur_step_nid or _make_id(cur_proc or cur_job or stem)
                    rel = "writes" if re.search(r"DISP=\(?\s*(?:NEW|MOD)\b", body, re.I) else "reads"
                    edges.append(_mf_edge(src_nid, dn, rel, str_path, loc))
            continue
        name, op, operands = m.group(1), m.group(2).upper(), m.group(3)
        prev_was_dd = (op == "DD")
        owner_nid = _make_id(cur_proc) if cur_proc else (_make_id(cur_job) if cur_job else file_nid)
        scope_label = cur_proc or cur_job or stem
        if op == "JOB":
            cur_job = name or stem
            cur_proc = None
            jid = _make_id(cur_job)
            _add(jid, cur_job, loc)
            edges.append(_mf_edge(file_nid, jid, "defines", str_path, loc))
        elif op == "PROC" and name:
            cur_proc = name
            pid = _make_id(name)
            _add(pid, name, loc)
            edges.append(_mf_edge(file_nid, pid, "defines", str_path, loc))
        elif op == "PEND":
            cur_proc = None
        elif op == "EXEC":
            step = name or f"STEP{i + 1}"
            cur_step_nid = _make_id(scope_label, step)
            _add(cur_step_nid, step, loc)
            edges.append(_mf_edge(owner_nid, cur_step_nid, "defines", str_path, loc))
            pgm = re.search(r"\bPGM=([A-Z0-9#@$.]+)", operands, re.I)
            proc = re.search(r"\bPROC=([A-Z0-9#@$.]+)", operands, re.I)
            ims = re.search(r"\bPARM=[('\"]*\s*(?:DLI|DBB)\s*,\s*([A-Z0-9#@$]+)\s*,\s*([A-Z0-9#@$]+)", operands, re.I) \
                if pgm and pgm.group(1).upper() in ("DFSRRC00", "DFSRRC10") else None
            if ims:
                # IMS batch/BMP region controller: PARM=(DLI,appprogram,psb,...)
                app, psb = ims.group(1), ims.group(2)
                an = _make_id(app)
                _add(an, app)
                edges.append(_mf_edge(cur_step_nid, an, "executes", str_path, loc))
                pn = _make_id(psb)
                _add(pn, psb)
                edges.append(_mf_edge(an, pn, "uses", str_path, loc, conf="INFERRED", score=0.8))
            elif pgm:
                tn = _make_id(pgm.group(1))
                _add(tn, pgm.group(1))
                edges.append(_mf_edge(cur_step_nid, tn, "executes", str_path, loc))
            elif proc:
                tn = _make_id(proc.group(1))
                _add(tn, proc.group(1))
                edges.append(_mf_edge(cur_step_nid, tn, "calls", str_path, loc))
            else:
                first = re.match(r"^([A-Z0-9#@$.]+)", operands.strip(), re.I)
                if first and first.group(1).upper() not in ("PGM", "PROC"):
                    tn = _make_id(first.group(1))
                    _add(tn, first.group(1))
                    edges.append(_mf_edge(cur_step_nid, tn, "calls", str_path, loc, conf="INFERRED", score=0.7))
        elif op == "DD":
            dsn = re.search(r"\bDSN(?:AME)?=([A-Z0-9#@$.()+\-]+)", operands, re.I)
            if dsn:
                name_only = dsn.group(1).split("(")[0]
                dn = _make_id("dsn", name_only)
                _add(dn, name_only, ftype="concept")
                src_nid = cur_step_nid or owner_nid
                rel = "writes" if re.search(r"DISP=\(?\s*(?:NEW|MOD)\b", operands, re.I) else "reads"
                edges.append(_mf_edge(src_nid, dn, rel, str_path, loc))
        elif op == "INCLUDE":
            mem = re.search(r"\bMEMBER=([A-Z0-9#@$]+)", operands, re.I)
            if mem:
                tn = _make_id(mem.group(1))
                _add(tn, mem.group(1))
                edges.append(_mf_edge(file_nid, tn, "includes", str_path, loc))
    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


def extract_pli(path: Path) -> dict:
    """Extract procedures/entries, %INCLUDE members, FETCH targets, and CALL
    relationships from a PL/I source file."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None) -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc))
            seen.add(nid)

    clean = re.sub(r"/\*.*?\*/", lambda m: _blank_keep_newlines(m.group(0)), src, flags=re.S)

    def _line_of(idx: int) -> str:
        return f"L{clean.count(chr(10), 0, idx) + 1}"

    procs: list[str] = []
    for m in re.finditer(r"(?im)^[^\S\n]*([A-Z_@#$][\w@#$]*)[ \t]*:[ \t]*(?:PROC(?:EDURE)?|ENTRY)\b", clean):
        name = m.group(1)
        nid = _make_id(name)
        _add(nid, name, _line_of(m.start()))
        edges.append(_mf_edge(file_nid, nid, "defines", str_path, _line_of(m.start())))
        procs.append(name)
    caller = _make_id(procs[0]) if procs else file_nid

    for m in re.finditer(r"(?i)%[ \t]*INCLUDE[ \t]+(?:[\w@#$]+[ \t]*\([ \t]*([\w@#$]+)[ \t]*\)|([\w@#$]+))", clean):
        member = m.group(1) or m.group(2)
        if not member:
            continue
        tn = _make_id(member)
        _add(tn, member)
        edges.append(_mf_edge(file_nid, tn, "includes", str_path, _line_of(m.start())))

    for m in re.finditer(r"(?i)\bFETCH[ \t]+([A-Z_@#$][\w@#$]*)", clean):
        tn = _make_id(m.group(1))
        _add(tn, m.group(1))
        edges.append(_mf_edge(caller, tn, "calls", str_path, _line_of(m.start()), conf="INFERRED", score=0.7))

    for m in re.finditer(r"(?i)\bCALL[ \t]+([A-Z_@#$][\w@#$]*)", clean):
        if m.group(1).upper() == "PLIRETC":
            continue
        edges.append(_mf_edge(caller, _make_id(m.group(1)), "calls", str_path, _line_of(m.start()),
                              conf="INFERRED", score=0.7))

    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


def extract_rexx(path: Path) -> dict:
    """Extract internal routines (labels) plus CALL and internal-function-call
    relationships from a REXX exec."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    str_path = str(path)
    stem = _file_stem(path).split(".")[-1]
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}
    routines: dict[str, str] = {}  # UPPER name -> node id

    def _add(nid: str, label: str, loc: str | None = None) -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc))
            seen.add(nid)

    clean = re.sub(r"/\*.*?\*/", lambda m: _blank_keep_newlines(m.group(0)), src, flags=re.S)
    for i, ln in enumerate(clean.split("\n")):
        m = re.match(r"^[ \t]*([A-Za-z_@#$!?][\w@#$!?.]*)[ \t]*:(?![=])", ln)
        if not m or re.match(r"(?i)^[ \t]*(?:if|when|otherwise|select|do|else|then|end)\b", ln):
            continue
        name = m.group(1)
        nid = _make_id(stem, name)
        _add(nid, name, f"L{i + 1}")
        routines[name.upper()] = nid
        edges.append(_mf_edge(file_nid, nid, "defines", str_path, f"L{i + 1}"))

    for m in re.finditer(r"(?i)\bCALL[ \t]+([A-Za-z_@#$!?][\w@#$!?.]*)", clean):
        callee = m.group(1)
        if callee.upper() in ("ON", "OFF"):
            continue  # CALL ON/OFF <condition> — signal trap, not a routine
        line = f"L{clean.count(chr(10), 0, m.start()) + 1}"
        edges.append(_mf_edge(file_nid, _make_id(stem, callee), "calls", str_path, line,
                              conf="INFERRED", score=0.7))

    # Internal function-style invocations: NAME(...) where NAME is a label.
    for m in re.finditer(r"(?i)\b([A-Za-z_@#$!?][\w@#$!?.]*)[ \t]*\(", clean):
        nid = routines.get(m.group(1).upper())
        if nid is None:
            continue
        line = f"L{clean.count(chr(10), 0, m.start()) + 1}"
        edges.append(_mf_edge(file_nid, nid, "calls", str_path, line, conf="INFERRED", score=0.7))

    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


# ── HLASM (IBM High Level Assembler / mainframe assembler) ────────────────────

def _hlasm_lines(src: str) -> list[str]:
    """Return HLASM source with the columns-73-80 identification field removed and
    full-line comments (``*`` in column 1, ``.*`` open-code macro comments) blanked
    out — newlines preserved so offsets/line numbers stay aligned."""
    out = []
    for ln in src.splitlines():
        s = ln[:72] if len(ln) > 72 else ln
        st = s.lstrip()
        out.append("" if (s[:1] == "*" or st[:2] == ".*") else s.rstrip())
    return out


def extract_hlasm(path: Path) -> dict:
    """Extract control sections (CSECT/RSECT/DSECT/START/COM), macro definitions,
    ENTRY/EXTRN linkage, COPY includes, ``=V(...)``/``=A(...)`` external address
    constants, and program-invocation macros (CALL / LINK / XCTL / ATTACH / LOAD ...)
    from an IBM High Level Assembler (HLASM, mainframe assembler) source file."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None, ftype: str = "code") -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc, ftype))
            seen.add(nid)

    lines = _hlasm_lines(src)
    text = "\n".join(lines)
    line_starts = [0]
    for ln in lines:
        line_starts.append(line_starts[-1] + len(ln) + 1)

    def _line_no(idx: int) -> int:
        return bisect.bisect_right(line_starts, idx)

    sect_index: list[tuple[int, str]] = []  # (line, control-section node id)
    in_macro = False
    pending_proto = False
    for i, ln in enumerate(lines):
        if pending_proto and ln.strip():
            pm = re.match(r"^(?:[A-Za-z@#$&][\w@#$&]*)?\s+([A-Za-z@#$][\w@#$]*)", ln)
            if pm:
                nid = _make_id(pm.group(1))
                _add(nid, pm.group(1), f"L{i + 1}")
                edges.append(_mf_edge(file_nid, nid, "defines", str_path, f"L{i + 1}"))
            pending_proto = False
            continue
        if re.match(r"^\s+MACRO\s*$", ln) or ln.strip().upper() == "MACRO":
            in_macro = True
            pending_proto = True
            continue
        if re.match(r"^\s+MEND\b", ln):
            in_macro = False
            continue
        if in_macro:
            continue
        m = re.match(r"^([A-Za-z@#$][\w@#$]*)\s+(CSECT|RSECT|DSECT|START|COM)\b", ln)
        if m:
            nid = _make_id(m.group(1))
            _add(nid, m.group(1), f"L{i + 1}")
            edges.append(_mf_edge(file_nid, nid, "defines", str_path, f"L{i + 1}"))
            sect_index.append((i + 1, nid))

    def _scope_at(line_no: int) -> str:
        if not sect_index:
            return file_nid
        pos = bisect.bisect_right(sect_index, (line_no, "￿")) - 1
        return sect_index[pos][1] if pos >= 0 else file_nid

    def _names(raw: str):
        for n in re.split(r"[,()\s]+", raw.strip()):
            if n and re.match(r"^[A-Za-z@#$][\w@#$]*$", n):
                yield n

    # ENTRY name[,name...]  → this module defines/exports those entry points.
    for m in re.finditer(r"(?im)^(?:[A-Za-z@#$][\w@#$]*)?[ \t]+ENTRY[ \t]+([A-Za-z@#$][\w@#$,() \t]*)", text):
        for name in _names(m.group(1)):
            nid = _make_id(name)
            _add(nid, name)
            edges.append(_mf_edge(_scope_at(_line_no(m.start())), nid, "defines", str_path, f"L{_line_no(m.start())}"))
    # EXTRN / WXTRN name[,...]  → external symbols this module references.
    for m in re.finditer(r"(?im)^(?:[A-Za-z@#$][\w@#$]*)?[ \t]+W?XTRN[ \t]+([A-Za-z@#$][\w@#$,() \t]*)", text):
        for name in _names(m.group(1)):
            nid = _make_id(name)
            _add(nid, name)
            edges.append(_mf_edge(_scope_at(_line_no(m.start())), nid, "calls", str_path, f"L{_line_no(m.start())}", conf="INFERRED", score=0.6))
    # COPY member  → assembler source/macro include.
    for m in re.finditer(r"(?im)^(?:[A-Za-z@#$][\w@#$]*)?[ \t]+COPY[ \t]+([A-Za-z@#$][\w@#$]*)", text):
        nid = _make_id(m.group(1))
        _add(nid, m.group(1))
        edges.append(_mf_edge(file_nid, nid, "includes", str_path, f"L{_line_no(m.start())}"))
    # =V(NAME) / =A(NAME) external address constants → external routine reference.
    for m in re.finditer(r"=[VA]\(([A-Za-z@#$][\w@#$]*)\)", text):
        nid = _make_id(m.group(1))
        _add(nid, m.group(1))
        edges.append(_mf_edge(_scope_at(_line_no(m.start())), nid, "calls", str_path, f"L{_line_no(m.start())}", conf="INFERRED", score=0.6))
    # CALL name,...  (the assembler CALL macro — first positional operand is the program/entry)
    for m in re.finditer(r"(?im)^(?:[A-Za-z@#$][\w@#$]*)?[ \t]+CALL[ \t]+([A-Za-z@#$][\w@#$]*)", text):
        name = m.group(1)
        if name.upper() in ("EP", "EPLOC", "DE", "VL", "MF", "SF", "ID", "LIST"):
            continue
        nid = _make_id(name)
        _add(nid, name)
        edges.append(_mf_edge(_scope_at(_line_no(m.start())), nid, "calls", str_path, f"L{_line_no(m.start())}"))
    # LINK/XCTL/ATTACH/LOAD/...  EP=name  (the only operand form we can resolve)
    for m in re.finditer(r"(?im)^(?:[A-Za-z@#$][\w@#$]*)?[ \t]+(?:LINK|LINKX|XCTL|XCTLX|ATTACH|ATTACHX|LOAD|CDLOAD|SYNCH|SYNCHX)\b[^\n]*?\bEP=([A-Za-z@#$][\w@#$]*)", text):
        nid = _make_id(m.group(1))
        _add(nid, m.group(1))
        edges.append(_mf_edge(_scope_at(_line_no(m.start())), nid, "calls", str_path, f"L{_line_no(m.start())}"))

    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


# ── IMS DBD / PSB source ─────────────────────────────────────────────────────

def _ims_logical_statements(src: str) -> list[tuple[int, str]]:
    """Join HLASM-style continuation lines (non-blank in column 72 → continued at
    column 16 of the next line) and drop comments. Returns (first-line-no, statement)."""
    out: list[tuple[int, str]] = []
    cur, cur_line = "", 0
    for i, ln in enumerate(src.splitlines()):
        body = ln[:71]
        cont = len(ln) > 71 and ln[71:72].strip() != ""
        if not cur and body.lstrip()[:1] == "*":
            continue
        if not cur:
            cur_line = i + 1
        cur += (" " + body.strip()) if cur else body.strip()
        if not cont:
            if cur.strip():
                out.append((cur_line, cur.strip()))
            cur = ""
    if cur.strip():
        out.append((cur_line, cur.strip()))
    return out


def _ims_kv(stmt: str) -> dict[str, str]:
    return {k.upper(): v.strip("()'") for k, v in re.findall(r"([A-Za-z][\w]*)\s*=\s*([A-Za-z0-9@#$.()'\-]+)", stmt)}


def extract_ims(path: Path) -> dict:
    """Extract IMS database structure from a DBD (Database Description) or PSB
    (Program Specification Block) source member: databases, segments and their
    parent hierarchy, PCBs and their target databases / sensitive segments."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None, ftype: str = "concept") -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc, ftype))
            seen.add(nid)

    cur_db_name: str | None = None
    cur_seg_name: str | None = None
    cur_pcb_nid: str | None = None
    cur_pcb_dbname: str | None = None
    pcb_n = 0
    stem = _file_stem(path).split(".")[-1]
    # The PSB's identity is its member name (= file stem); that is what JCL
    # `PARM=(DLI,prog,psb)` and the program reference. Created lazily on the first
    # PCB/PSBGEN so program → PSB → PCB → DBD → segment resolves across files.
    psb_nid = _make_id(stem)
    psb_created = False

    def _ensure_psb(loc: str | None = None) -> str:
        nonlocal psb_created
        if not psb_created:
            psb_created = True
            _add(psb_nid, stem, loc, ftype="code")
            edges.append(_mf_edge(file_nid, psb_nid, "defines", str_path, loc))
        return psb_nid

    def _seg_nid(dbname: str, segname: str) -> str:
        return _make_id("seg", dbname, segname)

    _IMS_KEYWORDS = {"DBD", "DATASET", "AREA", "SEGM", "FIELD", "LCHILD", "XDFLD", "DFSMARSH",
                     "PCB", "SENSEG", "SENFLD", "PSBGEN", "DBDGEN", "ACCESS"}
    for line_no, stmt in _ims_logical_statements(src):
        toks = stmt.split(None, 2)
        # Statements are usually "<blanks>KEYWORD operands"; tolerate an optional label.
        if toks and toks[0].upper() in _IMS_KEYWORDS:
            kw = toks[0].upper()
        elif len(toks) > 1 and toks[1].upper() in _IMS_KEYWORDS:
            kw = toks[1].upper()
        else:
            continue
        kv = _ims_kv(stmt)
        loc = f"L{line_no}"
        if kw == "DBD":
            cur_db_name = (kv.get("NAME") or "").split(",")[0].strip()
            cur_seg_name = None
            if cur_db_name:
                dn = _make_id("dbd", cur_db_name)
                _add(dn, cur_db_name, loc)
                edges.append(_mf_edge(file_nid, dn, "defines", str_path, loc))
        elif kw == "SEGM" and cur_db_name:
            name = (kv.get("NAME") or "").split(",")[0].strip()
            if not name:
                continue
            cur_seg_name = name
            snid = _seg_nid(cur_db_name, name)
            _add(snid, name, loc)
            parent = (kv.get("PARENT") or "0").split(",")[0].strip().strip("()")
            if parent and parent != "0":
                pnid = _seg_nid(cur_db_name, parent)
                _add(pnid, parent)
                edges.append(_mf_edge(pnid, snid, "contains", str_path, loc))
            else:
                edges.append(_mf_edge(_make_id("dbd", cur_db_name), snid, "contains", str_path, loc))
        elif kw == "LCHILD" and cur_db_name and cur_seg_name:
            name = (kv.get("NAME") or "").split(",")[0].strip()
            if name:
                cnid = _seg_nid(cur_db_name, name)
                _add(cnid, name)
                edges.append(_mf_edge(_seg_nid(cur_db_name, cur_seg_name), cnid, "references", str_path, loc, conf="INFERRED", score=0.6))
        elif kw == "PCB":
            pcb_n += 1
            pcbname = (kv.get("PCBNAME") or "").strip()
            cur_pcb_nid = _make_id("pcb", pcbname) if pcbname else _make_id("pcb", stem, str(pcb_n))
            _add(cur_pcb_nid, pcbname or f"PCB{pcb_n}", loc)
            edges.append(_mf_edge(_ensure_psb(loc), cur_pcb_nid, "contains", str_path, loc))
            cur_pcb_dbname = (kv.get("DBDNAME") or kv.get("NAME") or "").split(",")[0].strip() or None
            if cur_pcb_dbname:
                tn = _make_id("dbd", cur_pcb_dbname)
                _add(tn, cur_pcb_dbname)
                edges.append(_mf_edge(cur_pcb_nid, tn, "uses", str_path, loc))
        elif kw == "SENSEG" and cur_pcb_nid:
            name = (kv.get("NAME") or "").split(",")[0].strip()
            if name and cur_pcb_dbname:
                snid = _seg_nid(cur_pcb_dbname, name)
                _add(snid, name)
                edges.append(_mf_edge(cur_pcb_nid, snid, "uses", str_path, loc, conf="INFERRED", score=0.8))
        elif kw == "PSBGEN":
            _ensure_psb(loc)
            psbname = (kv.get("PSBNAME") or "").strip()
            if psbname:  # prefer the declared PSB name as the label
                for n in nodes:
                    if n["id"] == psb_nid:
                        n["label"] = psbname
                        break

    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


# ── CICS BMS (Basic Mapping Support) map source ──────────────────────────────

def extract_bms(path: Path) -> dict:
    """Extract CICS BMS mapset / map structure (DFHMSD mapsets and DFHMDI maps)
    from a BMS macro source file. Map nodes use the same id scheme as COBOL
    ``EXEC CICS SEND/RECEIVE MAP(...)`` references, so screen flow links up."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None, ftype: str = "code") -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc, ftype))
            seen.add(nid)

    cur_mapset: str | None = None
    for line_no, stmt in _ims_logical_statements(src):
        m = re.match(r"^([A-Za-z@#$][\w@#$]*)?\s+(DFHMSD|DFHMDI)\b", stmt)
        if not m:
            continue
        label, macro = m.group(1), m.group(2).upper()
        loc = f"L{line_no}"
        if macro == "DFHMSD":
            if re.search(r"\bTYPE\s*=\s*&?\(?\s*FINAL", stmt, re.I):
                cur_mapset = None
                continue
            if label:
                cur_mapset = _make_id(label)
                _add(cur_mapset, label, loc)
                edges.append(_mf_edge(file_nid, cur_mapset, "defines", str_path, loc))
        elif macro == "DFHMDI" and label:
            mnid = _make_id("map", label)
            _add(mnid, label, loc, ftype="concept")
            edges.append(_mf_edge(cur_mapset or file_nid, mnid, "defines", str_path, loc))
    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


# ── DB2 / SQL DDL ────────────────────────────────────────────────────────────

def extract_ddl(path: Path) -> dict:
    """Extract DDL objects (tables, views, indexes, procedures, triggers,
    tablespaces, ...) and foreign-key references. Uses the tree-sitter SQL
    extractor when ``tree-sitter-sql`` is installed; otherwise a dependency-free
    regex extractor that also understands DB2-specific ``CREATE`` statements."""
    r = extract_sql(path)
    if "error" not in r:
        return r
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"error": f"cannot read {path}"}
    clean = re.sub(r"--[^\n]*", "", src)
    clean = re.sub(r"/\*.*?\*/", lambda m: _blank_keep_newlines(m.group(0)), clean, flags=re.S)
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [_mf_node(file_nid, path.name, str_path)]
    edges: list[dict] = []
    seen: set[str] = {file_nid}

    def _add(nid: str, label: str, loc: str | None = None, ftype: str = "code") -> None:
        if nid not in seen:
            nodes.append(_mf_node(nid, label, str_path, loc, ftype))
            seen.add(nid)

    def _line(idx: int) -> str:
        return f"L{clean.count(chr(10), 0, idx) + 1}"

    def _qn(raw: str) -> str:
        return raw.strip().strip('"').strip()

    _OBJ_RE = (r"(?is)\bCREATE\s+(?:OR\s+REPLACE\s+)?(TABLE|VIEW|TABLESPACE|STOGROUP|DATABASE|"
               r"INDEX|UNIQUE\s+INDEX|ALIAS|SYNONYM|PROCEDURE|FUNCTION|TRIGGER|SEQUENCE|TYPE)\s+"
               r"(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_\"][\w\".$#@-]*)")
    creates: list[tuple[int, str]] = []  # (offset, qualified table name) for FK source resolution
    for m in re.finditer(_OBJ_RE, clean):
        kind = re.sub(r"\s+", " ", m.group(1).upper())
        name = _qn(m.group(2))
        is_relation = kind in ("TABLE", "VIEW", "ALIAS", "SYNONYM", "SEQUENCE")
        ftype = "concept" if is_relation or kind in ("TABLESPACE", "STOGROUP", "DATABASE", "INDEX", "UNIQUE INDEX") else "code"
        nid = _sql_table_id(name) if is_relation else _make_id(kind.split()[-1].lower(), name)
        _add(nid, name, _line(m.start()), ftype=ftype)
        edges.append(_mf_edge(file_nid, nid, "defines", str_path, _line(m.start())))
        if kind == "TABLE":
            creates.append((m.start(), name))
        if kind in ("INDEX", "UNIQUE INDEX", "TRIGGER"):
            on = re.search(r"\bON\s+([A-Za-z_\"][\w\".$#@-]*)", clean[m.end():m.end() + 300])
            if on:
                tn = _sql_table_id(on.group(1))
                _add(tn, _qn(on.group(1)), ftype="concept")
                edges.append(_mf_edge(nid, tn, "references", str_path, _line(m.start()), conf="INFERRED", score=0.7))
    for m in re.finditer(r"(?is)\bREFERENCES\s+([A-Za-z_\"][\w\".$#@-]*)", clean):
        tgt = _qn(m.group(1))
        tn = _sql_table_id(tgt)
        _add(tn, tgt, ftype="concept")
        src_name = next((nm for off, nm in reversed(creates) if off < m.start()), None)
        src_nid = _sql_table_id(src_name) if src_name else file_nid
        edges.append(_mf_edge(src_nid, tn, "references", str_path, _line(m.start()), conf="INFERRED", score=0.8))
    return {"nodes": nodes, "edges": _mf_self_consistent(nodes, edges)}


def extract_verilog(path: Path) -> dict:
    """Extract modules, functions, tasks, package imports, and instantiations from .v/.sv files."""
    try:
        import tree_sitter_verilog as tsverilog
        from tree_sitter import Language, Parser
    except ImportError:
        return {"nodes": [], "edges": [], "error": "tree_sitter_verilog not installed"}

    try:
        language = Language(tsverilog.language())
        parser = Parser(language)
        source = path.read_bytes()
        tree = parser.parse(source)
        root = tree.root_node
    except Exception as e:
        return {"nodes": [], "edges": [], "error": str(e)}

    stem = _file_stem(path)
    str_path = str(path)
    nodes: list[dict] = []
    edges: list[dict] = []
    seen_ids: set[str] = set()

    def add_node(nid: str, label: str, line: int) -> None:
        if nid not in seen_ids:
            seen_ids.add(nid)
            nodes.append({"id": nid, "label": label, "file_type": "code",
                          "source_file": str_path, "source_location": f"L{line}",
                          "confidence_score": 1.0})

    def add_edge(src: str, tgt: str, relation: str, line: int,
                 confidence: str = "EXTRACTED", score: float = 1.0) -> None:
        edges.append({"source": src, "target": tgt, "relation": relation,
                      "confidence": confidence, "confidence_score": score,
                      "source_file": str_path, "source_location": f"L{line}", "weight": 1.0})

    file_nid = _make_id(str(path))
    add_node(file_nid, path.name, 1)

    def walk(node, module_nid: str | None = None) -> None:
        t = node.type

        if t == "module_declaration":
            name_node = node.child_by_field_name("name")
            if name_node:
                mod_name = _read_text(name_node, source)
                line = node.start_point[0] + 1
                nid = _make_id(stem, mod_name)
                add_node(nid, mod_name, line)
                add_edge(file_nid, nid, "defines", line)
                for child in node.children:
                    walk(child, nid)
                return

        elif t in ("function_declaration", "function_prototype"):
            name_node = node.child_by_field_name("name")
            if name_node:
                func_name = _read_text(name_node, source)
                line = node.start_point[0] + 1
                parent = module_nid or file_nid
                nid = _make_id(parent, func_name)
                add_node(nid, f"{func_name}()", line)
                add_edge(parent, nid, "contains", line)

        elif t == "task_declaration":
            name_node = node.child_by_field_name("name")
            if name_node:
                task_name = _read_text(name_node, source)
                line = node.start_point[0] + 1
                parent = module_nid or file_nid
                nid = _make_id(parent, task_name)
                add_node(nid, task_name, line)
                add_edge(parent, nid, "contains", line)

        elif t == "package_import_declaration":
            for child in node.children:
                if child.type == "package_import_item":
                    pkg_text = _read_text(child, source)
                    pkg_name = pkg_text.split("::")[0].strip()
                    if pkg_name:
                        line = node.start_point[0] + 1
                        tgt_nid = _make_id(pkg_name)
                        add_node(tgt_nid, pkg_name, line)
                        src = module_nid or file_nid
                        add_edge(src, tgt_nid, "imports_from", line)

        elif t == "module_instantiation":
            # module_type instantiates another module
            type_node = node.child_by_field_name("module_type")
            if type_node and module_nid:
                inst_type = _read_text(type_node, source).strip()
                if inst_type:
                    line = node.start_point[0] + 1
                    tgt_nid = _make_id(inst_type)
                    add_node(tgt_nid, inst_type, line)
                    add_edge(module_nid, tgt_nid, "instantiates", line)

        for child in node.children:
            walk(child, module_nid)

    walk(root)
    return {"nodes": nodes, "edges": edges}


def extract_sql(path: Path) -> dict:
    """Extract tables, views, functions, and relationships from .sql files via tree-sitter."""
    try:
        import tree_sitter_sql as tssql
        from tree_sitter import Language, Parser
    except ImportError:
        return {"nodes": [], "edges": [], "error": "tree_sitter_sql not installed. Run: pip install tree-sitter-sql"}

    try:
        language = Language(tssql.language())
        parser = Parser(language)
        source = path.read_bytes()
        tree = parser.parse(source)
        root = tree.root_node
    except Exception as e:
        return {"nodes": [], "edges": [], "error": str(e)}

    stem = re.sub(r"[^a-z0-9]", "_", path.stem.lower())
    str_path = str(path)
    file_nid = _make_id(str_path)
    nodes: list[dict] = [{"id": file_nid, "label": path.name, "file_type": "code",
                           "source_file": str_path, "source_location": None}]
    edges: list[dict] = []
    seen_ids: set[str] = {file_nid}
    table_nids: dict[str, str] = {}  # name → nid for reference resolution

    def _read(n) -> str:
        return source[n.start_byte:n.end_byte].decode("utf-8", errors="replace")

    def _obj_name(n) -> str | None:
        for c in n.children:
            if c.type == "object_reference":
                return _read(c)
        return None

    def _add_node(nid: str, label: str, line: int) -> None:
        if nid not in seen_ids:
            seen_ids.add(nid)
            nodes.append({"id": nid, "label": label, "file_type": "code",
                           "source_file": str_path, "source_location": f"L{line}"})
            edges.append({"source": file_nid, "target": nid, "relation": "contains",
                           "confidence": "EXTRACTED", "source_file": str_path,
                           "source_location": f"L{line}", "weight": 1.0})

    def _add_edge(src: str, tgt: str, relation: str, line: int) -> None:
        edges.append({"source": src, "target": tgt, "relation": relation,
                       "confidence": "EXTRACTED", "source_file": str_path,
                       "source_location": f"L{line}", "weight": 1.0})

    def walk(node) -> None:
        t = node.type
        line = node.start_point[0] + 1

        if t == "create_table":
            name = _obj_name(node)
            if name:
                nid = _sql_table_id(name)
                _add_node(nid, name, line)
                table_nids[name.lower()] = nid
                # Foreign keys: both column-level (REFERENCES on a column_definition)
                # and table-level (FOREIGN KEY ... REFERENCES in a constraints block).
                def _refs_in(container) -> None:
                    for cd in container.children:
                        if cd.type == "constraints":
                            _refs_in(cd)
                            continue
                        if cd.type not in ("column_definition", "constraint"):
                            continue
                        ref_name: str | None = None
                        found_ref = False
                        for cc in cd.children:
                            if cc.type == "keyword_references":
                                found_ref = True
                            elif found_ref and cc.type == "object_reference":
                                ref_name = _read(cc)
                                break
                        if ref_name:
                            _add_edge(nid, _sql_table_id(ref_name), "references", line)

                for col in node.children:
                    if col.type == "column_definitions":
                        _refs_in(col)

        elif t == "create_view":
            name = _obj_name(node)
            if name:
                nid = _sql_table_id(name)
                _add_node(nid, name, line)
                table_nids[name.lower()] = nid
                # FROM/JOIN table references inside view body
                _walk_from_refs(node, nid, line)

        elif t == "create_function":
            name = _obj_name(node)
            if name:
                nid = _make_id(stem, name)
                _add_node(nid, f"{name}()", line)
                _walk_from_refs(node, nid, line)

        elif t == "create_procedure":
            name = _obj_name(node)
            if name:
                nid = _make_id(stem, name)
                _add_node(nid, f"{name}()", line)
                _walk_from_refs(node, nid, line)

        elif t == "alter_table":
            name = _obj_name(node)
            if name:
                src_nid = table_nids.get(name.lower())
                if not src_nid:
                    src_nid = _sql_table_id(name)
                    _add_node(src_nid, name, line)
                    table_nids[name.lower()] = src_nid
                for child in node.children:
                    if child.type == "add_constraint":
                        for cc in child.children:
                            if cc.type != "constraint":
                                continue
                            found_ref = False
                            ref_name: str | None = None
                            for ccc in cc.children:
                                if ccc.type == "keyword_references":
                                    found_ref = True
                                elif found_ref and ccc.type == "object_reference":
                                    ref_name = _read(ccc)
                                    break
                            if ref_name:
                                ref_nid = table_nids.get(ref_name.lower())
                                if not ref_nid:
                                    ref_nid = _sql_table_id(ref_name)
                                _add_edge(src_nid, ref_nid, "references", line)

        for child in node.children:
            walk(child)

    def _walk_from_refs(node, caller_nid: str, line: int) -> None:
        """Recursively find FROM/JOIN table references inside a node."""
        if node.type in ("from", "join"):
            for c in node.children:
                if c.type == "relation":
                    for cc in c.children:
                        if cc.type == "object_reference":
                            tbl = _read(cc)
                            tbl_nid = _sql_table_id(tbl)
                            _add_edge(caller_nid, tbl_nid, "reads_from",
                                      c.start_point[0] + 1)
        for child in node.children:
            _walk_from_refs(child, caller_nid, line)

    for stmt in root.children:
        if stmt.type == "statement":
            for child in stmt.children:
                walk(child)

    return {"nodes": nodes, "edges": edges}


